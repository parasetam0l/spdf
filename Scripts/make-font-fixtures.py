#!/usr/bin/env python3
"""P03-010/P03-011/P14-026: regenerate the embedded test-font artifacts.

Downloads DejaVu Sans 2.37 (Bitstream Vera license, permissive) and emits
Tools/PDFFixtures/FontFixtureData.swift with two subsets: the original
space/A/B/C/U+00E2/U+FB01 program (plus its CFF conversion) and a
multilingual Greek/Cyrillic/Hebrew program, each with the measured metrics
the PDF builders need. The committed Swift file is the deterministic
artifact; rerun only when the font source changes.

Requires: fontTools (python3 -m pip install --user fonttools), curl, unzip.
"""
import base64
import os
import subprocess
import sys
import tempfile

DEJAVU_ZIP = (
    "https://downloads.sourceforge.net/project/dejavu/dejavu/2.37/"
    "dejavu-fonts-ttf-2.37.zip"
)
UNICODES = "U+0041,U+0042,U+0043,U+00E2,U+FB01,U+0020"
# P14-026: a second, multilingual subset (Greek, Cyrillic, Hebrew) under the
# same permissive license, for extraction/geometry verification. Codes are
# chosen for the PDF fixture; scalars drive the subset and metrics.
MULTILINGUAL_UNICODES = (
    "U+0020,U+0391,U+0392,U+0393,U+0411,U+0412,U+05D0,U+05D1,U+05E9"
)
MULTILINGUAL_CODES = {
    0x20: 0x0020, 0x41: 0x0391, 0x42: 0x0392, 0x43: 0x0393,
    0x44: 0x0411, 0x45: 0x0412, 0x46: 0x05D0, 0x47: 0x05D1,
    0x48: 0x05E9,
}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Tools", "PDFFixtures", "FontFixtureData.swift")


def run(*argv):
    subprocess.run(argv, check=True)


def main():
    from fontTools.ttLib import TTFont

    work = tempfile.mkdtemp(prefix="spdf-font-fixture-")
    archive = os.path.join(work, "dejavu.zip")
    run("curl", "-sL", "-o", archive, DEJAVU_ZIP)
    run("unzip", "-o", "-q", archive, "dejavu-fonts-ttf-2.37/ttf/DejaVuSans.ttf",
        "-d", work)
    source = os.path.join(work, "dejavu-fonts-ttf-2.37", "ttf", "DejaVuSans.ttf")
    subset = os.path.join(work, "subset.ttf")
    run(sys.executable, "-m", "fontTools.subset", source,
        "--output-file=" + subset, "--unicodes=" + UNICODES,
        "--layout-features=*", "--name-IDs=*", "--glyph-names",
        "--notdef-outline")
    multilingual = os.path.join(work, "multilingual.ttf")
    run(sys.executable, "-m", "fontTools.subset", source,
        "--output-file=" + multilingual, "--unicodes=" + MULTILINGUAL_UNICODES,
        "--layout-features=*", "--name-IDs=*", "--glyph-names",
        "--notdef-outline")
    font = TTFont(subset)
    with open(subset, "rb") as handle:
        program = handle.read()
    multilingual_font = TTFont(multilingual)
    with open(multilingual, "rb") as handle:
        multilingual_program = handle.read()
    multilingual_cmap = multilingual_font.getBestCmap()
    multilingual_advances = {}
    for code, scalar in sorted(MULTILINGUAL_CODES.items()):
        glyph_name = multilingual_cmap[scalar]
        advance, _ = multilingual_font["hmtx"][glyph_name]
        multilingual_advances[code] = int(
            round(advance * 1000 / multilingual_font["head"].unitsPerEm))
    # P15-020: the same subset converted to CFF-flavored OpenType
    # (quadratic to cubic outline conversion) for the composite CFF path.
    otf_path = os.path.join(work, "subset.otf")
    convert_to_cff(subset, otf_path)
    with open(otf_path, "rb") as handle:
        cff_program = handle.read()
    units = font["head"].unitsPerEm
    widths = {}
    for code, glyph in [(0x20, "space"), (0x41, "A"), (0x42, "B"),
                        (0x43, "C")]:
        advance, _ = font["hmtx"][glyph]
        widths[code] = int(round(advance * 1000 / units))
    # fi is addressed through Differences code 1, not WinAnsi.
    fi_advance, _ = font["hmtx"]["fi"]
    head = font["head"]
    hhea = font["hhea"]
    # Wrap at 160 columns for readable diffs.
    def wrapped(data):
        encoded = base64.b64encode(data).decode("ascii")
        assert len(encoded) < 65536, "subset unexpectedly large"
        lines = [encoded[i:i + 160] for i in range(0, len(encoded), 160)]
        literal = "\n".join(f'    "{line}" +' for line in lines[:-1])
        return literal + f'\n    "{lines[-1]}"'
    literal = wrapped(program)
    cff_literal = wrapped(cff_program)
    multilingual_literal = wrapped(multilingual_program)
    widths_literal = ",\n    ".join(f"{code}: {w}" for code, w in sorted(widths.items()))
    multilingual_literal_widths = ",\n    ".join(
        f"{code}: {w}" for code, w in sorted(multilingual_advances.items()))
    with open(OUT, "w") as handle:
        handle.write(f"""import Foundation

/// P03-010/P03-011: test-only embedded font program. A DejaVu Sans 2.37
/// subset (space, A, B, C, a, acircumflex, circumflex, U+FB01 fi ligature; {len(program)} bytes) under the
/// permissive Bitstream Vera license (see Tests/Fixtures/DejaVu-LICENSE.txt
/// and Docs/ThirdPartyNotices.md). Generated by Scripts/make-font-fixtures.py;
/// do not hand-edit (rerun the script instead).
public enum FontFixtureData {{
  /// The subset TrueType program (FontFile2 payload).
  public static let subsetProgramBase64 =
{literal}
  /// The CFF-flavored conversion of the same subset (FontFile3 payload).
  public static let cffProgramBase64 =
{cff_literal}
  /// WinAnsi code to advance width in thousandths of an em.
  public static let winAnsiWidths: [Int: Int] = [
    {widths_literal}
  ]
  /// P14-026: a DejaVu Sans 2.37 subset covering Greek (U+0391–U+0393),
  /// Cyrillic (U+0411–U+0412), and Hebrew (U+05D0–U+05E9) plus space
  /// ({len(multilingual_program)} bytes), under the same permissive license.
  public static let multilingualProgramBase64 =
{multilingual_literal}
  /// Fixture code to advance width in thousandths of an em for the
  /// multilingual subset (from the program's own metrics).
  public static let multilingualWidths: [Int: Int] = [
    {multilingual_literal_widths}
  ]
  /// Advance of the fi ligature (Differences code 1).
  public static let fiWidth = {int(round(fi_advance * 1000 / units))}
  public static let unitsPerEm = {units}
  public static let fontBBox: [Int] = [{head.xMin}, {head.yMin}, {head.xMax}, {head.yMax}]
  public static let ascent = {hhea.ascent}
  public static let descent = {hhea.descent}
}}
""")
    print(f"wrote {OUT} ({len(program)} font bytes)")


def convert_to_cff(source, destination):
    """Convert a TrueType subset to CFF-flavored OpenType in place."""
    from fontTools.ttLib import TTFont, newTable
    from fontTools.pens.cu2quPen import Cu2QuPen
    from fontTools.pens.t2CharStringPen import T2CharStringPen
    from fontTools.cffLib import (
        CFFFontSet, TopDict, TopDictIndex, CharStrings, FontDict,
        PrivateDict, GlobalSubrsIndex,
    )

    font = TTFont(source)
    glyphOrder = font.getGlyphOrder()
    glyphSet = font.getGlyphSet()
    charstrings = {}
    for name in glyphOrder:
        pen = T2CharStringPen(width=font["hmtx"][name][0], glyphSet=glyphSet)
        cuPen = Cu2QuPen(pen, max_err=1.0, reverse_direction=True)
        font["glyf"][name].draw(cuPen, glyphSet)
        charstrings[name] = pen.getCharString()
    cff = CFFFontSet()
    cff.major, cff.minor, cff.hdrSize, cff.offSize = 1, 0, 4, 4
    cff.GlobalSubrs = GlobalSubrsIndex()
    top = TopDict()
    top.charset = glyphOrder
    top.FontBBox = [
        font["head"].xMin, font["head"].yMin,
        font["head"].xMax, font["head"].yMax,
    ]
    top.Private = PrivateDict()
    cs = CharStrings(None, glyphOrder, [], None, None, None)
    for name in glyphOrder:
        cs[name] = charstrings[name]
    top.CharStrings = cs
    top.FontName = "DejaVuSans"
    cff.topDictIndex = TopDictIndex()
    cff.topDictIndex.items = [top]
    cff.fontNames = ["DejaVuSans"]

    out = TTFont()
    out.recalcBBoxes = False
    # Determinism: fontTools would otherwise stamp head.modified with the
    # current time, making the committed artifact change on every rerun.
    out.recalcTimestamp = False
    # CFF-flavored OpenType identifies as OTTO; TrueType 0x00010000 would
    # make consumers look for glyf/loca and reject the font.
    out.sfntVersion = "OTTO"
    out.setGlyphOrder(glyphOrder)
    for tag in ["head", "hhea", "hmtx", "cmap", "name", "post", "OS/2"]:
        out[tag] = font[tag]
    maxp = newTable("maxp")
    maxp.tableVersion = 0x00005000
    maxp.numGlyphs = len(glyphOrder)
    out["maxp"] = maxp
    out["CFF "] = newTable("CFF ")
    out["CFF "].cff = cff
    out.save(destination)


if __name__ == "__main__":
    main()
