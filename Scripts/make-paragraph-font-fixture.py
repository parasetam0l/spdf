#!/usr/bin/env python3
"""Generate the licensed ASCII subset used by imported-paragraph fixtures.

Requires fontTools. Accepts an optional local official DejaVu2.37 .tar.bz2
archive; otherwise downloads the release. No installed/system font is copied.
"""
import base64
import io
from pathlib import Path
import sys
import tarfile
import urllib.request
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
url = ('https://github.com/dejavu-fonts/dejavu-fonts/releases/download/'
       'version_2_37/dejavu-fonts-ttf-2.37.tar.bz2')
archive = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(url).read()
with tarfile.open(fileobj=io.BytesIO(archive), mode='r:bz2') as package:
    program = package.extractfile('dejavu-fonts-ttf-2.37/ttf/DejaVuSans.ttf').read()
font = TTFont(io.BytesIO(program), recalcTimestamp=False)
options = subset.Options()
options.name_IDs = ['*']
options.glyph_names = True
options.notdef_outline = True
engine = subset.Subsetter(options=options)
engine.populate(unicodes=range(32, 127))
engine.subset(font)
glyphs = font.getBestCmap()
# CID PDF subsets need their glyph programs, not a Unicode cmap. Exercise
# the native preview's PDF-to-GID bridge instead of relying on a full font.
del font['cmap']
payload = io.BytesIO()
font.save(payload)
encoded = base64.b64encode(payload.getvalue()).decode('ascii')
chunks = [encoded[i:i+160] for i in range(0, len(encoded), 160)]
literal = '\n'.join('    "'+chunk+'"'+(' +' if i < len(chunks)-1 else '') for i, chunk in enumerate(chunks))
units = font['head'].unitsPerEm
records = []
for code, name in sorted(glyphs.items()):
    width = round(font['hmtx'][name][0] * 1000 / units)
    records.append(f'    {code}: ({font.getGlyphID(name)}, {width})')
out = root/'Tools/PDFFixtures/ParagraphFontFixture.swift'
out.write_text('''import Foundation

/// DejaVu Sans2.37, ASCII CID subset without a Unicode cmap.
/// Bitstream Vera license.
/// See Tests/Fixtures/DejaVu-LICENSE.txt and Docs/ThirdPartyNotices.md.
/// Generated by Scripts/make-paragraph-font-fixture.py; test data only.
public enum ParagraphFontFixture {
  public static let programBase64 =
'''+literal+'''
  public static let glyphs: [Int: (id: Int, width: Int)] = [
'''+',\n'.join(records)+'''
  ]
}
''')
print(f'Generated {out.name}: {len(payload.getvalue())} font bytes, {len(records)} glyph mappings.')
