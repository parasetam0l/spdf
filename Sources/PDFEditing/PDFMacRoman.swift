/// PDF's MacRomanEncoding (ISO 32000-1, Annex D and Table 115).
/// This is deliberately separate from the Macintosh cmap encoding used by
/// TrueType fonts: PDF leaves fifteen Macintosh slots undefined, uses currency
/// rather than Euro at 219, and gives the duplicate space at 202 the same
/// Unicode text as code 32. Word spacing still applies only to code 32.
enum PDFMacRoman {
  static let characters: [UInt8: Character] = {
    var result: [UInt8: Character] = [:]
    for code in UInt8(32)...126 { result[code] = Character(UnicodeScalar(code)) }
    let high: [UInt32?] = [
      // 128–159
      0xC4, 0xC5, 0xC7, 0xC9, 0xD1, 0xD6, 0xDC, 0xE1,
      0xE0, 0xE2, 0xE4, 0xE3, 0xE5, 0xE7, 0xE9, 0xE8,
      0xEA, 0xEB, 0xED, 0xEC, 0xEE, 0xEF, 0xF1, 0xF3,
      0xF2, 0xF4, 0xF6, 0xF5, 0xFA, 0xF9, 0xFB, 0xFC,
      // 160–191
      0x2020, 0xB0, 0xA2, 0xA3, 0xA7, 0x2022, 0xB6, 0xDF,
      0xAE, 0xA9, 0x2122, 0xB4, 0xA8, nil, 0xC6, 0xD8,
      nil, 0xB1, nil, nil, 0xA5, 0xB5, nil, nil,
      nil, nil, nil, 0xAA, 0xBA, nil, 0xE6, 0xF8,
      // 192–223
      0xBF, 0xA1, 0xAC, nil, 0x192, nil, nil, 0xAB,
      0xBB, 0x2026, 0x20, 0xC0, 0xC3, 0xD5, 0x152, 0x153,
      0x2013, 0x2014, 0x201C, 0x201D, 0x2018, 0x2019, 0xF7, nil,
      0xFF, 0x178, 0x2044, 0xA4, 0x2039, 0x203A, 0xFB01, 0xFB02,
      // 224–255
      0x2021, 0xB7, 0x201A, 0x201E, 0x2030, 0xC2, 0xCA, 0xC1,
      0xCB, 0xC8, 0xCD, 0xCE, 0xCF, 0xCC, 0xD3, 0xD4,
      nil, 0xD2, 0xDA, 0xDB, 0xD9, 0x131, 0x2C6, 0x2DC,
      0xAF, 0x2D8, 0x2D9, 0x2DA, 0xB8, 0x2DD, 0x2DB, 0x2C7,
    ]
    for (offset, value) in high.enumerated() {
      if let scalar = value.flatMap(UnicodeScalar.init) {
        result[UInt8(offset + 128)] = Character(scalar)
      }
    }
    return result
  }()

  /// Ascending codes give the ordinary space precedence over its duplicate.
  static let codes: [Character: [UInt8]] = {
    var result: [Character: [UInt8]] = [:]
    for (code, character) in characters.sorted(by: { $0.key < $1.key }) {
      result[character, default: []].append(code)
    }
    return result
  }()
}
